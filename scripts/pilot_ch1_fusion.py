"""Chapter 1 follow-up pilot: late fusion of neighbouring epochs, and the learning-curve ceiling.

1. Late fusion (bit positions 1-3, shrinkage LDA, within subject, leave-one-session-out).
   Low-dimensional scores, each cross-fitted inside the training sessions (inner leave-one-session-out):
     a(t) = LDA(x_t)     -> y_t        (the thesis decoder)
     b(t) = LDA(x_{t+1}) -> y_t        (late response of t inside the next epoch)
     c(t) = LDA(x_{t-1}) -> y_t        (control: should carry ~nothing about y_t)
     a(t-1), a(t+1)                    (neighbours' own evidence, to explain their overlap away)
   A logistic regression stacks the training-set scores; test scores come from LDAs fitted on all training sessions.
2. Learning-curve ceiling: per-subject fit of acc(n) = a - b * n^-c to lc_1..lc_5 of reports/pilot_ch1_headroom.csv.

Usage: python scripts/pilot_ch1_fusion.py   -> reports/pilot_ch1_fusion.md
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
from scipy.optimize import curve_fit
from scipy.stats import wilcoxon
from sklearn.linear_model import LogisticRegression

from pilot_ch1_headroom import SUBJECTS, fit_lda, flat, load, neighbours

ROOT = Path(__file__).resolve().parents[1]
STACKS = {"a": ["a"], "a+b": ["a", "b"], "a+c": ["a", "c"], "a+b+c": ["a", "b", "c"],
          "a+nb": ["a", "ap", "an"], "a+b+nb": ["a", "b", "ap", "an"]}


def scores(F, y, src_tr, tgt_tr, src_te, sessions_tr):
    """Cross-fitted training scores and test scores of an LDA mapping features F[src] to labels y[tgt]."""
    s_tr = np.zeros(len(src_tr))
    for k in np.unique(sessions_tr):
        inn, out = sessions_tr != k, sessions_tr == k
        w, b = fit_lda(F[src_tr[inn]], y[tgt_tr[inn]])
        s_tr[out] = F[src_tr[out]] @ w + b
    w, b = fit_lda(F[src_tr], y[tgt_tr])
    return s_tr, F[src_te] @ w + b


def main():
    rows = []
    for s in SUBJECTS:
        d = load(s)
        prev, nxt = neighbours(d)
        ok = ~d["artifact"]
        mid = ok & (prev >= 0) & (nxt >= 0) & (d["bit"] >= 1) & (d["bit"] <= 3)
        mid &= ok[np.maximum(prev, 0)] & ok[np.maximum(nxt, 0)]
        F, y = flat(d["X"]), d["y"]
        res = {}
        for k in range(1, 7):
            itr, ite = np.flatnonzero((d["session"] != k) & mid), np.flatnonzero((d["session"] == k) & mid)
            sess = d["session"][itr]
            # the own-trial decoder a() is trained on all bit positions of the training sessions
            all_tr = np.flatnonzero((d["session"] != k) & ok)
            a_all_tr = np.zeros(len(y))
            for kk in np.unique(d["session"][all_tr]):
                inn = all_tr[d["session"][all_tr] != kk]
                w, b = fit_lda(F[inn], y[inn])
                sel = np.flatnonzero((d["session"] == kk) & ok)
                a_all_tr[sel] = F[sel] @ w + b
            w, b = fit_lda(F[all_tr], y[all_tr])
            te_mask = d["session"] == k
            a_all_tr[te_mask] = F[te_mask] @ w + b
            S_tr = {"a": a_all_tr[itr], "ap": a_all_tr[prev[itr]], "an": a_all_tr[nxt[itr]]}
            S_te = {"a": a_all_tr[ite], "ap": a_all_tr[prev[ite]], "an": a_all_tr[nxt[ite]]}
            S_tr["b"], S_te["b"] = scores(F, y, nxt[itr], itr, nxt[ite], sess)
            S_tr["c"], S_te["c"] = scores(F, y, prev[itr], itr, prev[ite], sess)
            for name, cols in STACKS.items():
                lr = LogisticRegression(C=1.0).fit(np.column_stack([S_tr[c] for c in cols]), y[itr])
                pred = lr.predict(np.column_stack([S_te[c] for c in cols]))
                res.setdefault(name, []).append(((pred == y[ite]).mean(), len(ite)))
            res.setdefault("b_alone", []).append((((S_te["b"] > 0) == y[ite]).mean(), len(ite)))
        rows.append({m: 100 * sum(a * n for a, n in v) / sum(n for _, n in v) for m, v in res.items()})
        print(f"Sub{s:02d} " + " ".join(f"{m} {v:.1f}" for m, v in rows[-1].items()), flush=True)
    df = pd.DataFrame(rows, index=list(SUBJECTS))

    def line(m, ref="a"):
        dlt = df[m] - df[ref]
        p = wilcoxon(df[m], df[ref]).pvalue if (dlt != 0).any() else 1.0
        return f"| `{m}` | {df[m].mean():.2f} | {dlt.mean():+.2f} | {(dlt > 0).sum()}/28 | {p:.1g} |"
    out = ["# Chapter 1 follow-up: late fusion of neighbouring epochs and the learning-curve ceiling", "",
           "Generated by `scripts/pilot_ch1_fusion.py`. Shrinkage LDA, within subject, leave-one-session-out, "
           "bit positions 1-3.", "",
           "a = own epoch → y_t; b = next epoch → y_t; c = previous epoch → y_t (control); "
           "nb = neighbours' own scores a(t-1), a(t+1).", "",
           "| Stack | Accuracy (%) | Δ vs a (pp) | Improved | p |", "|---|---|---|---|---|"]
    out += [line(m) for m in ["b_alone", *STACKS]]

    # learning-curve ceiling
    lc = pd.read_csv(ROOT / "reports/pilot_ch1_headroom.csv", index_col=0)[[f"lc_{n}" for n in range(1, 6)]]
    n = np.arange(1, 6, dtype=float)
    f = lambda n, a, b, c: a - b * n ** (-c)            # noqa: E731
    fits = []
    for _, r in lc.iterrows():
        try:
            p, _ = curve_fit(f, n, r.to_numpy(), p0=(r.iloc[-1] + 1, 5, 1), bounds=([40, 0, 0.2], [100, 100, 4]),
                             maxfev=20000)
        except RuntimeError:
            p = (np.nan,) * 3
        fits.append(p)
    fits = np.array(fits)
    gap = fits[:, 0] - lc["lc_5"].to_numpy()
    lc_mean = lc.mean()
    pm, _ = curve_fit(f, n, lc_mean.to_numpy(), p0=(76, 5, 1), bounds=([40, 0, 0.2], [100, 100, 4]))
    sess_equiv = lambda acc: (pm[1] / (pm[0] - acc)) ** (1 / pm[2])   # noqa: E731
    out += ["", "## Learning curve (W0, all bit positions)", "",
            "| Own training sessions | 1 | 2 | 3 | 4 | 5 |", "|---|---|---|---|---|---|",
            "| Accuracy (%) | " + " | ".join(f"{v:.2f}" for v in lc_mean) + " |", "",
            f"Fit of the mean curve, acc(n) = a − b·n^(−c): a = {pm[0]:.2f}%, b = {pm[1]:.2f}, c = {pm[2]:.2f}.",
            f"- Asymptote (unlimited own calibration data, same linear decoder): **{pm[0]:.2f}%**, i.e. "
            f"**{pm[0] - lc_mean['lc_5']:+.2f} pp** above 5 sessions "
            f"(per-subject fits: median gap {np.nanmedian(gap):+.2f} pp).",
            f"- Under this curve, +0.81 pp at 5 sessions corresponds to "
            f"{sess_equiv(lc_mean['lc_5'] + 0.81):.1f} sessions of calibration data "
            f"(+0.44 pp corresponds to {sess_equiv(lc_mean['lc_5'] + 0.44):.1f})."]
    (ROOT / "reports/pilot_ch1_fusion.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
