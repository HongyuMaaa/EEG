"""Aggregate all runs under results/ into results/summary.md and results/summary.csv.

Usage:
    python scripts/summarize_results.py [--results-dir results]

Subject accuracy = accuracy over all of that subject's test trials (pooled over its test folds).
Reported per method / protocol: mean and standard deviation over subjects (seeds averaged first),
and the number of completed folds, so incomplete runs are visible.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

EXPECTED_FOLDS = {"within": 168, "pooled": 6, "loso": 28}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results-dir", default="results")
    args = ap.parse_args()
    root = Path(args.results_dir)

    rows, status = [], []
    for run in sorted(root.glob("*/*/seed*")):
        method, protocol, seed = run.parts[-3], run.parts[-2], int(run.name[4:])
        preds = sorted((run / "predictions").glob("*.csv"))
        info = json.loads((run / "run_info.json").read_text()) if (run / "run_info.json").exists() else {}
        status.append({"method": method, "protocol": protocol, "seed": seed, "folds_done": len(preds),
                       "folds_expected": EXPECTED_FOLDS.get(protocol), "device": info.get("device"),
                       "max_epochs_override": info.get("max_epochs_override")})
        if not preds:
            continue
        p = pd.concat([pd.read_csv(f) for f in preds])
        for s, g in p.groupby("subject"):
            rows.append({"method": method, "protocol": protocol, "seed": seed, "subject": s,
                         "accuracy": (g.y == g.pred).mean(), "n_test": len(g)})
    if not rows:
        print("no results found")
        return

    per_subject = pd.DataFrame(rows)
    by_subject = per_subject.groupby(["method", "protocol", "subject"], as_index=False).accuracy.mean()
    summary = by_subject.groupby(["method", "protocol"]).accuracy.agg(["mean", "std", "min", "max", "count"])
    summary = summary.rename(columns={"count": "n_subjects"}).reset_index()
    per_subject.to_csv(root / "summary_per_subject.csv", index=False)
    summary.to_csv(root / "summary.csv", index=False)

    st = pd.DataFrame(status)
    lines = ["# Results summary", "", "Generated by `scripts/summarize_results.py`.", "",
             "## Accuracy (mean ± std over subjects)", "",
             "| method | protocol | accuracy | min | max | subjects |", "|---|---|---|---|---|---|"]
    for r in summary.itertuples():
        lines.append(f"| {r.method} | {r.protocol} | {100 * r.mean:.2f} ± {100 * (r.std if r.n_subjects > 1 else 0):.2f} "
                     f"| {100 * r.min:.2f} | {100 * r.max:.2f} | {r.n_subjects} |")
    lines += ["", "## Run status", "", "| method | protocol | seed | folds done | expected | device | epochs override |",
              "|---|---|---|---|---|---|---|"]
    for r in st.itertuples():
        lines.append(f"| {r.method} | {r.protocol} | {r.seed} | {r.folds_done} | {r.folds_expected} | {r.device} "
                     f"| {r.max_epochs_override or ''} |")
    wide = by_subject.pivot_table(index="subject", columns=["protocol", "method"], values="accuracy")
    cols = list(wide.columns)
    lines += ["", "## Accuracy per subject (%)", "",
              "| subject | " + " | ".join(f"{m} ({p})" for p, m in cols) + " |", "|---|" + "---|" * len(cols)]
    for s, r in wide.iterrows():
        lines.append(f"| Sub{s:02d} | " + " | ".join("" if pd.isna(r[c]) else f"{100 * r[c]:.2f}" for c in cols) + " |")
    (root / "summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[:8 + len(summary)]))


if __name__ == "__main__":
    main()
